export function languageFor(languages = []) {
  for (const locale of languages) {
    const lang = String(locale).toLowerCase().split(/[-_]/)[0];
    if (Object.hasOwn(translations, lang))
      return { lang, locale: String(locale).replaceAll("_", "-") };
  }
  return { lang: "en", locale: "en" };
}
export function actionName(kind, strings) {
  return strings.actions[kind?.split(".")[1]] || strings.tap;
}

export function labelFor(label, strings) {
  return Object.hasOwn(strings.labels, label) ? strings.labels[label] : label;
}
